param(
    [ValidateSet('Launcher', 'Api', 'Web')]
    [string]$Role = 'Launcher'
)

$ErrorActionPreference = 'Stop'
$ProjectRoot = Split-Path -Parent $MyInvocation.MyCommand.Path

function Write-Failure([string]$Message) {
    Write-Host "`n$Message" -ForegroundColor Red
    if ($Role -eq 'Launcher') { Read-Host 'Press Enter to close' | Out-Null }
    exit 1
}

function Find-Java25 {
    $candidates = @()
    if ($env:JAVA_HOME) { $candidates += $env:JAVA_HOME }
    $candidates += @(
        'C:\Program Files\Eclipse Adoptium',
        'C:\Program Files\Microsoft',
        'C:\Program Files\Java'
    ) | ForEach-Object {
        if (Test-Path $_) {
            Get-ChildItem -LiteralPath $_ -Directory -ErrorAction SilentlyContinue |
                Where-Object { $_.Name -match 'jdk.*25' } |
                ForEach-Object { $_.FullName }
        }
    }

    foreach ($candidate in ($candidates | Select-Object -Unique)) {
        $compiler = Join-Path $candidate 'bin\javac.exe'
        if (Test-Path $compiler) {
            $versionText = (& $compiler -version 2>&1 | Out-String).Trim()
            if ($versionText -match 'javac\s+25(?:\.|$)') { return $candidate }
        }
    }
    return $null
}

function Set-Java25 {
    $javaHome = Find-Java25
    if (-not $javaHome) { Write-Failure 'Java 25 was not found. Install Temurin JDK 25, then run this launcher again.' }
    $env:JAVA_HOME = $javaHome
    $env:Path = "$javaHome\bin;$env:Path"
    Write-Host "Using JAVA_HOME=$javaHome" -ForegroundColor Green
}

function Read-EnvValue([string]$Name, [string]$DefaultValue) {
    $line = Get-Content -LiteralPath (Join-Path $ProjectRoot '.env') |
        Where-Object { $_ -match "^$Name=" } | Select-Object -First 1
    if ($line) { return $line.Substring($Name.Length + 1) }
    return $DefaultValue
}

if ($Role -eq 'Api') {
    Set-Java25
    Set-Location (Join-Path $ProjectRoot 'backend')
    $browserCache = Join-Path $env:LOCALAPPDATA 'ms-playwright'
    $chromiumFound = Test-Path $browserCache -and
        [bool](Get-ChildItem -LiteralPath $browserCache -Directory -Filter 'chromium-*' -ErrorAction SilentlyContinue | Select-Object -First 1)
    if (-not $chromiumFound) {
        Write-Host 'Installing the Playwright Chromium browser (first launch only)...' -ForegroundColor Yellow
        & mvn exec:java '-Dexec.mainClass=com.microsoft.playwright.CLI' '-Dexec.args=install chromium'
        if ($LASTEXITCODE -ne 0) { Write-Failure 'Playwright Chromium installation failed. Check the Maven output above, then run the launcher again.' }
    }
    Write-Host 'Starting the Spring Boot API...' -ForegroundColor Green
    & mvn spring-boot:run
    exit $LASTEXITCODE
}

if ($Role -eq 'Web') {
    Set-Location (Join-Path $ProjectRoot 'frontend')
    if (-not (Test-Path 'node_modules')) {
        Write-Host 'Installing frontend dependencies (first launch only)...' -ForegroundColor Yellow
        & npm ci
        if ($LASTEXITCODE -ne 0) { Write-Failure 'npm ci failed. Check the npm output above, then run the launcher again.' }
    }
    Write-Host 'Starting the React app...' -ForegroundColor Green
    & npm run dev
    exit $LASTEXITCODE
}

Set-Location $ProjectRoot
Write-Host 'Price Monitor - local launcher' -ForegroundColor Cyan

if (-not (Test-Path '.env')) {
    $randomBytes = New-Object byte[] 32
    $randomGenerator = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $randomGenerator.GetBytes($randomBytes)
    $randomGenerator.Dispose()
    $localPassword = ($randomBytes | ForEach-Object { $_.ToString('x2') }) -join ''
    @(
        '# Local-only settings generated by Start-PriceMonitor.ps1.'
        'DB_NAME=price_monitor'
        'DB_USERNAME=price_monitor'
        "DB_PASSWORD=$localPassword"
        'VAPID_PUBLIC_KEY='
        'VAPID_PRIVATE_KEY='
        'VAPID_SUBJECT=mailto:you@example.com'
    ) | Out-File -LiteralPath '.env' -Encoding ascii
    Write-Host 'Created .env with a random local database password. It is ignored by Git.' -ForegroundColor Green
}

Set-Java25
$compilerVersion = (& (Join-Path $env:JAVA_HOME 'bin\javac.exe') -version 2>&1 | Out-String).Trim()
Write-Host $compilerVersion
if (-not (Get-Command mvn -ErrorAction SilentlyContinue)) { Write-Failure 'Maven was not found on PATH. Install Maven and open a new terminal.' }
$mavenInfo = (& mvn -version 2>&1 | Out-String)
if ($LASTEXITCODE -ne 0 -or $mavenInfo -notmatch 'Java version:\s+25(?:\.|\s)') {
    Write-Failure 'Maven did not start with Java 25. Confirm mvn is installed, then reopen this launcher.'
}
Write-Host (($mavenInfo -split "`r?`n" | Select-Object -First 4) -join "`n")

if (-not (Get-Command node -ErrorAction SilentlyContinue) -or -not (Get-Command npm -ErrorAction SilentlyContinue)) {
    Write-Failure 'Node.js and npm are required for the frontend. Install Node.js LTS, then run the launcher again.'
}
$nodeVersion = ((& node --version 2>&1 | Out-String).Trim() -replace '^v', '')
if ([version]$nodeVersion -lt [version]'20.19.0') { Write-Failure "Node.js $nodeVersion is too old. Install Node.js 20.19 or newer LTS." }
Write-Host "Node.js v$nodeVersion; npm $(& npm --version)" -ForegroundColor Green

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    $dockerCli = Join-Path $env:ProgramFiles 'Docker\Docker\resources\bin'
    if (Test-Path (Join-Path $dockerCli 'docker.exe')) { $env:Path = "$dockerCli;$env:Path" }
}
if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    Write-Failure 'Docker CLI is not installed or is not on PATH. Finish Docker Desktop and WSL 2 setup, open a fresh terminal, then double-click this launcher again.'
}
$composeInfo = (& docker compose version 2>&1 | Out-String).Trim()
if ($LASTEXITCODE -ne 0) { Write-Failure 'Docker Compose is unavailable. Finish Docker Desktop setup, then run this launcher again.' }
Write-Host $composeInfo -ForegroundColor Green

& docker info *> $null
if ($LASTEXITCODE -ne 0) {
    $desktopPaths = @(
        (Join-Path $env:ProgramFiles 'Docker\Docker\Docker Desktop.exe'),
        (Join-Path $env:LOCALAPPDATA 'Programs\Docker\Docker\Docker Desktop.exe')
    )
    $desktop = $desktopPaths | Where-Object { Test-Path $_ } | Select-Object -First 1
    if (-not $desktop) { Write-Failure 'Docker Desktop is installed but its engine is not running. Open Docker Desktop, finish any WSL setup prompts, wait for it to say Engine running, and retry.' }
    Write-Host 'Starting Docker Desktop and waiting for its engine...' -ForegroundColor Yellow
    Start-Process -FilePath $desktop
    $engineReady = $false
    for ($attempt = 0; $attempt -lt 90; $attempt++) {
        Start-Sleep -Seconds 2
        & docker info *> $null
        if ($LASTEXITCODE -eq 0) { $engineReady = $true; break }
    }
    if (-not $engineReady) { Write-Failure 'Docker Desktop did not become ready. Complete its WSL 2 setup or reboot Windows if prompted, then retry.' }
}

$databaseName = Read-EnvValue 'DB_NAME' 'price_monitor'
$databaseUser = Read-EnvValue 'DB_USERNAME' 'price_monitor'
Write-Host 'Starting PostgreSQL...' -ForegroundColor Cyan
& docker compose up -d postgres
if ($LASTEXITCODE -ne 0) { Write-Failure 'PostgreSQL did not start. Check Docker Desktop and the .env settings.' }
$databaseReady = $false
for ($attempt = 0; $attempt -lt 60; $attempt++) {
    & docker compose exec -T postgres pg_isready -U $databaseUser -d $databaseName *> $null
    if ($LASTEXITCODE -eq 0) { $databaseReady = $true; break }
    Start-Sleep -Seconds 2
}
if (-not $databaseReady) { Write-Failure 'PostgreSQL is not ready yet. Check `docker compose logs postgres`, then retry.' }
Write-Host 'PostgreSQL is ready.' -ForegroundColor Green

foreach ($port in @(8080, 5173)) {
    $connection = New-Object System.Net.Sockets.TcpClient
    try { $connection.Connect('127.0.0.1', $port); $occupied = $true }
    catch { $occupied = $false }
    finally { $connection.Dispose() }
    if ($occupied) { Write-Failure "Port $port is already in use. Stop the existing process before starting another copy." }
}

$powershellExe = Join-Path $PSHOME 'powershell.exe'
Start-Process -FilePath $powershellExe -ArgumentList @('-NoExit', '-NoProfile', '-File', "`"$PSCommandPath`"", '-Role', 'Api')
Start-Process -FilePath $powershellExe -ArgumentList @('-NoExit', '-NoProfile', '-File', "`"$PSCommandPath`"", '-Role', 'Web')

Write-Host 'Waiting for the frontend to start...' -ForegroundColor Cyan
$webReady = $false
for ($attempt = 0; $attempt -lt 45; $attempt++) {
    Start-Sleep -Seconds 2
    $connection = New-Object System.Net.Sockets.TcpClient
    try { $connection.Connect('127.0.0.1', 5173); $webReady = $true }
    catch { $webReady = $false }
    finally { $connection.Dispose() }
    if ($webReady) { break }
}
if ($webReady) {
    Write-Host 'Opening http://localhost:5173' -ForegroundColor Green
    Start-Process 'http://localhost:5173'
    if (-not ((Read-EnvValue 'VAPID_PUBLIC_KEY' '') -and (Read-EnvValue 'VAPID_PRIVATE_KEY' ''))) {
        Write-Host 'Chrome price alerts are optional and are not configured yet. Add VAPID keys to .env to enable them.' -ForegroundColor Yellow
    }
} else {
    Write-Host 'The frontend did not answer on port 5173 yet. Check the React terminal for startup errors.' -ForegroundColor Yellow
}

Write-Host "`nApp URL: http://localhost:5173" -ForegroundColor Cyan
Write-Host 'Keep the API terminal and Docker Desktop running while monitoring prices.'
Read-Host 'Press Enter to close this launcher (the API and web terminals will stay open)' | Out-Null
